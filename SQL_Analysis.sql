,cte2 as (select year,month_name,tot_tickets,
lag(tot_tickets) over(order by year,month) as previous_mon_tckts ,
lag(tot_tickets,12) over(order by year,month) as previous_yr_tckts 
from cte)
select *,
round((tot_tickets-previous_mon_tckts)*100.0 / previous_mon_tckts,1) as MoM_pct,
round((tot_tickets-previous_yr_tckts)*100.0 / previous_yr_tckts,1) as YoY_pct
from cte2
order by year;
