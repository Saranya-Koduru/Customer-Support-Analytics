The largest recent increase is 16.5% in July 2026.
fOR YoY - It's more stable than MoM overall, with most monthly changes staying within roughly ±7% 
after the large +29.4% spike in Aug 2025. July 2026 then shows a notable +15.2% YoY increase.
Support demand is generally stable year-over-year, but experiences recurring short-term monthly fluctuations. 
